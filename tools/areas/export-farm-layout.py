"""Writes src/episodes/ep1/data/farmLayout.ts from the farmstead's plan (farmstead.py) in
Babylon space (x = -Blender x, z = -Blender y): its fence, paths, cart track, fields,
buildings, inner fences and groves, the roofs (the village road's shops among them), for what the game grows at runtime round them (the
tall grass) and keeps off them.

    blender -b --factory-startup -P tools/areas/export-farm-layout.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import farmstead as FS  # noqa: E402
import village_fields as VF  # noqa: E402
import village_road as VR  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "src", "episodes", "ep1", "data", "farmLayout.ts")


def n(v):
    v = -v + 0.0
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def rect(x0, x1, y0, y1):
    return f"{{ minX: {n(x1)}, maxX: {n(x0)}, minZ: {n(y1)}, maxZ: {n(y0)} }}"


def pt(p):
    return f"[{n(p[0])}, {n(p[1])}]"


buildings = [(-9, 9, 8, 36), FS.KITCHEN, FS.SERVANTS, FS.BARN, FS.TOOL_SHED, (26, 32, 2, 8), (31, 34, 28, 31),
             (FS.WELL[0] - 1.4, FS.WELL[0] + 1.4, FS.WELL[1] - 1.4, FS.WELL[1] + 1.4)]
# The paths out to the two old dry fields went with them (village_fields.clear, Nov 24).
paths = [(pts, half) for k, (pts, half) in enumerate(FS.PATHS) if k not in (8, 9)] + [FS.TRACK]
fields = [(x0, x1, y0, y1) for x0, x1, y0, y1, _kind in VF.PLOTS]
# The yard before the house (village_fields): no tall grass through the drying mats, the
# straw stack, the pounder's lean-to, the kre, the firewood or the bench.
yard = [(x - 1.3, x + 1.3, y - 1.8, y + 1.8) for x, y, _t in VF.DRYING] + \
    [(VF.STRAW_STACK[0] - 1.4, VF.STRAW_STACK[0] + 1.4, VF.STRAW_STACK[1] - 1.4, VF.STRAW_STACK[1] + 1.4),
     (VF.POUNDER[0] - 1.4, VF.POUNDER[0] + 1.4, VF.POUNDER[1] - 1.1, VF.POUNDER[1] + 1.1),
     (VF.KRE[0] - 1.2, VF.KRE[0] + 1.2, VF.KRE[1] - 0.9, VF.KRE[1] + 0.9),
     (VF.FIREWOOD[0] - 0.4, VF.FIREWOOD[0] + 0.4, VF.FIREWOOD[1], VF.FIREWOOD[2]),
     (VF.BENCH[0] - 0.8, VF.BENCH[0] + 0.8, VF.BENCH[1] - 0.4, VF.BENCH[1] + 0.4)]
buildings = buildings + yard


def eaves(r, e=0.9):
    return (r[0] - e, r[1] + e, r[2] - e, r[3] + e)


# The house (both blocks, the galleries, the veranda), the kitchen house, the barn, the
# servants' hut, the tool shed, the byre and the granary, each to its ridge.
roofs = [((-8.0 - 0.9, 8.0 + 0.9, 9.2, 34.0 + 0.9), 7.5), (eaves(FS.KITCHEN), 6.6), (eaves(FS.BARN), 6.0),
         (eaves(FS.SERVANTS), 4.6), (eaves(FS.TOOL_SHED, 0.6), 3.2), ((26.5, 31.5, 2.5, 7.5), 3.0),
         ((FS.GRANARY[0] - 1.6, FS.GRANARY[0] + 1.6, FS.GRANARY[1] - 1.6, FS.GRANARY[1] + 1.6), 3.6),
         ((VF.POUNDER[0] - 1.55, VF.POUNDER[0] + 1.55, VF.POUNDER[1] - 1.3, VF.POUNDER[1] + 1.3), 2.2)]
# The shops along the village road outside the gate (village_road.py, Nov 25, 2026): their
# verandas keep Sora dry.
roofs += VR.roof_rects()
fences = [(a, c) for a, c in FS._fence_lines()]

ts = f"""/**
 * The farmstead's plan (tools/areas/farmstead.py, the Nov 22, 2026 build, and its paddies and
 * yard, village_fields.py, Nov 24), in Babylon
 * space (x = -Blender x, z = -Blender y), metres. Generated by
 * tools/areas/export-farm-layout.py; do not edit by hand.
 */
import type {{ Rect }} from "./forestBorder";

/** The outer fence. */
export const FARM: Rect = {rect(*FS.FARM)};

/** Narrow mud paths and the cart track: points, and the half width trodden bare. */
export const FARM_PATHS: readonly {{ points: readonly (readonly [number, number])[]; half: number }}[] = [
{chr(10).join(f"  {{ points: [{', '.join(pt(p) for p in pts)}], half: {half} }}," for pts, half in paths)}
];

/** The rice paddies' plots (their own rice or stubble; village_fields.py, Nov 24, 2026). */
export const FIELDS: readonly Rect[] = [
{chr(10).join(f"  {rect(*f)}," for f in fields)}
];

/** The buildings and the well, with the ground round their doors (kept bare). */
export const BUILDINGS: readonly Rect[] = [
{chr(10).join(f"  {rect(*b)}," for b in buildings)}
];

/** The fences' lines (the outer fence, the barn yard's, the kitchen yard's). */
export const FENCES: readonly (readonly [readonly [number, number], readonly [number, number]])[] = [
{chr(10).join(f"  [{pt(a)}, {pt(c)}]," for a, c in fences)}
];

/** Roofs the rain doesn't fall through: the ground they cover (eaves included) and how high. */
export const ROOFS: readonly (Rect & {{ top: number }})[] = [
{chr(10).join(f"  {rect(*r)[:-2]}, top: {t} }}," for r, t in roofs)}
];

/** The groves: centre and radius. */
export const GROVES: readonly {{ x: number; z: number; r: number }}[] = [
{chr(10).join(f"  {{ x: {n(cx)}, z: {n(cy)}, r: {r} }}," for (cx, cy), r, _n, _k in FS.GROVES)}
];
"""
with open(OUT, "w") as f:
    f.write(ts)
print("wrote", OUT)

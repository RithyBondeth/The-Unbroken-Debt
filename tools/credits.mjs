#!/usr/bin/env node
// Builds the third-party credits list from docs/production/asset-tracker.csv into
// docs/production/credits.md, and reports what blocks release: assets in use whose
// licence or author is missing, unknown or unclear, or that are marked as blockers.
// Usage: npm run credits             (write the list, report blockers)
//        npm run credits -- --strict (also exit 1 if anything blocks release)

import { readFileSync, writeFileSync } from "node:fs";

const TRACKER = "docs/production/asset-tracker.csv";
const OUT = "docs/production/credits.md";
const strict = process.argv.includes("--strict");

/** RFC 4180 CSV: quoted fields may hold commas, newlines and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  const endField = () => {
    row.push(field);
    field = "";
  };
  const endRow = () => {
    endField();
    rows.push(row);
    row = [];
  };
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") endField();
    else if (c === "\n") endRow();
    else if (c !== "\r") field += c;
  }
  if (field || row.length) endRow();
  return rows.filter((r) => r.some((f) => f.trim()));
}

const [header, ...lines] = parseCsv(readFileSync(TRACKER, "utf8"));
const assets = lines.map((line) => Object.fromEntries(header.map((h, i) => [h, line[i] ?? ""])));

/** Made by the project alone: nothing to credit. */
const isProject = (a) => /^Project$/i.test(a.Author.trim()) && /^Project$/i.test(a.Licence.trim());
const inUse = (a) => a.Status !== "Not started";
const thirdParty = assets.filter((a) => inUse(a) && a.Author.trim() && !isProject(a));

const blockers = assets.filter(
  (a) =>
    inUse(a) &&
    (/RELEASE BLOCKER/.test(a.Notes) ||
      (/[LMK]/.test(a.Source) && !isProject(a) && (!a.Licence.trim() || !a.Author.trim())) ||
      /unknown|unclear|placeholder|to confirm/i.test(
        `${a.Licence} ${a.Author} ${a["Credit required"]}`,
      )),
);

/** Groups by author and licence, so a library contributor appears once with all their work. */
function groups(list) {
  const map = new Map();
  for (const a of list) {
    const key = `${a.Author.trim()}\u0000${a.Licence.trim()}`;
    if (!map.has(key))
      map.set(key, { author: a.Author.trim(), licence: a.Licence.trim(), assets: [] });
    map.get(key).assets.push(a);
  }
  return [...map.values()].sort((x, y) => x.author.localeCompare(y.author));
}

const source = (a) => a["Library / URL"].trim();
const link = (a) => (/^https?:\/\//.test(source(a)) ? `[${a.Asset}](${source(a)})` : a.Asset);

const md = [
  "# Third-party credits",
  "",
  `Generated by \`npm run credits\` from [asset-tracker.csv](asset-tracker.csv); do not edit by hand.`,
  "Only assets in use (status other than Not started) by someone other than the project are listed.",
  "",
  "| Author | Licence | Assets |",
  "|---|---|---|",
  ...groups(thirdParty).map(
    (g) =>
      `| ${g.author} | ${g.licence} | ${g.assets.map((a) => `${link(a)} (${a.ID})`).join(", ")} |`,
  ),
  "",
  "## Software",
  "",
  "| Package | Licence |",
  "|---|---|",
  "| Babylon.js (`@babylonjs/core`, `gui`, `loaders`, `ktx2decoder`) | Apache 2.0 |",
  "| Havok Physics for Babylon.js (`@babylonjs/havok`) | MIT |",
  "| idb-keyval | Apache 2.0 |",
  "| meshoptimizer decoder | MIT |",
  "",
  "## Release blockers",
  "",
  blockers.length
    ? blockers
        .map((a) => `- **${a.ID} ${a.Asset}**: ${a.Licence || "no licence"}. ${a.Notes}`)
        .join("\n")
    : "None.",
  "",
].join("\n");

writeFileSync(OUT, md);
console.log(
  `${OUT}: ${thirdParty.length} third-party assets in ${groups(thirdParty).length} credits.`,
);
if (blockers.length) {
  console.log(`\n${blockers.length} release blocker(s):`);
  for (const a of blockers) console.log(`  ${a.ID}  ${a.Asset}  [${a.Licence || "no licence"}]`);
  if (strict) process.exit(1);
}

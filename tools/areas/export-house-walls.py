"""Writes src/episodes/ep1/data/houseWalls.ts from the re-planned house's walls and their
door gaps (stilt_house.WALLS), in Babylon space (x = -Blender x, z = -Blender y), so the
Act II walker sees and walks through the same doorways the house was built with.

    blender -b --factory-startup -P tools/areas/export-house-walls.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import stilt_house as SH  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "src", "episodes", "ep1", "data", "houseWalls.ts")


def r(v):
    return f"{-v + 0.0:.2f}".rstrip("0").rstrip(".") if v else "0"


# Doorways nobody walks through: the nailed back door and the padlocked logs room.
SHUT = {(d[1], d[2], d[3]) for d in SH.DOORS if d[0] in ("back", "locked")}
rows = []
for name, along_x, lo, hi, a0, a1, doors, _windows, _out in SH.WALLS:
    at = r((lo + hi) / 2)
    gaps = ", ".join(f"[{r(b)}, {r(a)}]" for a, b in doors if (name, a, b) not in SHUT)
    rows.append(f'  {{ name: "{name}", along: "{"x" if along_x else "z"}", at: {at}, from: {r(a1)}, to: {r(a0)}, '
                f"gaps: [{gaps}] }},")

ts = f"""/**
 * The re-planned house's walls and the gaps of their doorways, on its floor (y = {SH.FLOOR}).
 * Generated by tools/areas/export-house-walls.py from tools/areas/stilt_house.py; do not
 * edit by hand. Babylon space, metres: a wall runs `along` x (at z = `at`) or z (at x =
 * `at`) from `from` to `to`; `gaps` are its doorways' spans along it (the nailed back
 * door and the padlocked logs room are not doorways here).
 */
export interface HouseWall {{
  name: string;
  along: "x" | "z";
  at: number;
  from: number;
  to: number;
  gaps: readonly (readonly [number, number])[];
}}

export const HOUSE_FLOOR = {SH.FLOOR};

export const HOUSE_WALLS: readonly HouseWall[] = [
{chr(10).join(rows)}
];
"""
with open(OUT, "w") as f:
    f.write(ts)
print("wrote", OUT, len(rows), "walls")
